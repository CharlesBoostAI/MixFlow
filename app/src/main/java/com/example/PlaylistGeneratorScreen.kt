// Format cumulative duration into French text eg "1 h 12 min" or "45 min 20 s"
private fun formatCumulativeDuration(seconds: Int): String {
    val h = seconds / 3600
    val m = (seconds % 3600) / 60
    val s = seconds % 60
    
    return when {
         h > 0 -> "${h}h ${m}m"
         m > 0 -> "${m}m ${s}s"
         else -> "${s}s"
    }
}

// Format track individual duration into standard MM:SS
private fun formatDuration(seconds: Int): String {
    val m = seconds / 60
    val s = seconds % 60
    return String.format("%d:%02d", m, s)
}

// Plain text playlist builder to export to Spotify/Notes
private fun formatPlaylistToText(genre: String, list: List<Track>, stats: String): String {
    val sb = java.lang.StringBuilder()
    sb.append("🎵 Ma Smart Playlist MixFlow - [$genre] ✨\n")
    sb.append("📊 Durée : $stats | ${list.size} titres\n")
    sb.append("----------------------------\n")
    list.forEachIndexed { index, track ->
        sb.append(String.format("%02d. %s - %s (%s)\n", index + 1, track.title, track.artist, formatDuration(track.durationSeconds)))
    }
    sb.append("----------------------------\n")
    sb.append("Créé avec MixFlow (Local Solver Offline)")
    return sb.toString()
}


